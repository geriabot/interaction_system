"""
Generate the Behavior Trees and the configuration of each ablation from the method's trees
(interaction_system_behaviors/behavior_tree_xml), so that an ablation differs from the method
only in the decision it removes. Run it after changing the method's trees:

    python3 make_ablations.py

Writes behavior_tree_xml/<ablation>/*.xml and config/<ablation>/interaction_behaviors_config.yaml.
The monolithic ablation is not generated: behavior_tree_xml/monolithic.xml is written by hand
(one tree for every strategy).
"""

import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
METHOD_XML = os.path.normpath(os.path.join(
    HERE, "..", "..", "..", "interaction_system_behaviors", "behavior_tree_xml"))
STRATEGIES = ["slot_filling", "explanation", "quiz", "procedure", "roleplay", "grounded_qa",
              "questionnaire"]

# The ablations made by editing the method's trees: {name: [(file, regex, replacement)]}
CANCEL_SKILL = r'skill="cancel_check"'
ABLATIONS = {
    # The spoken cancellation ends the dialogue as soon as it is detected (no confirmation)
    "no_cancel_confirmation": [
        ("common.xml", CANCEL_SKILL, 'skill="ablation.cancel_check_no_confirmation"'),
    ],
    # The cancel request detected by the LLM alone (no local fast path)
    "llm_only_cancel": [
        ("common.xml", CANCEL_SKILL, 'skill="ablation.cancel_check_llm_only"'),
    ],
    # The cancel request detected by keywords alone (no LLM)
    "keywords_only_cancel": [
        ("common.xml", CANCEL_SKILL, 'skill="ablation.cancel_check_keywords_only"'),
    ],
    # Slot filling closes as soon as the frame is complete, without reading it back
    "no_confirmation": [
        ("slot_filling.xml",
         r'(<Switch2 variable="\{label\}" case_1="complete" case_2="not_understood">)\s*'
         r'<AskIntelligence skill="slot_filling.confirmation_question"/>',
         '\\1\n'
         '        <Sequence>\n'
         '          <AskIntelligence skill="slot_filling.confirmed"/>\n'
         '          <Script code="done := true"/>\n'
         '        </Sequence>'),
    ],
}

CONFIG = """# Generated by make_ablations.py: the method's runtime with the trees of the ablation
# {name}. Launch: interaction_system.launch.py config_file:=<this file>
node_name: "interaction_system_bt_node"

orchestrator_type: "interaction_orchestrator"

package_name: "interaction_system"

orchestrator_libraries:
  - "libinteraction_system.so"

plugin_libraries:
  - "libinteraction_system_behaviors_bt_plugins.so"

behaviors:
{behaviors}"""

BEHAVIOR = """  - name: "interaction_{strategy}"
    behavior_file: "behavior_tree_xml/{path}"
    control_period_ms: 50
    package_name: "interaction_ablations"
"""


def write_config(name: str, paths: dict) -> None:
    os.makedirs(os.path.join(HERE, "config", name), exist_ok=True)
    behaviors = "".join(BEHAVIOR.format(strategy=s, path=paths[s]) for s in STRATEGIES)
    with open(os.path.join(HERE, "config", name, "interaction_behaviors_config.yaml"), "w") as f:
        f.write(CONFIG.format(name=name, behaviors=behaviors))


def main() -> None:
    for name, edits in ABLATIONS.items():
        out = os.path.join(HERE, "behavior_tree_xml", name)
        shutil.rmtree(out, ignore_errors=True)
        os.makedirs(out)
        for xml in os.listdir(METHOD_XML):
            if xml.endswith(".xml"):
                shutil.copy(os.path.join(METHOD_XML, xml), out)
        for file, pattern, replacement in edits:
            path = os.path.join(out, file)
            with open(path, encoding="utf-8") as f:
                text = f.read()
            text, n = re.subn(pattern, replacement, text)
            if n == 0:
                raise RuntimeError(f"{name}: the edit of {file} did not apply ({pattern})")
            note = f"<!-- Generated by make_ablations.py ({name}) from the method's {file} -->"
            text = text.replace("?>\n", "?>\n" + note + "\n", 1)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
        write_config(name, {s: f"{name}/{s}.xml" for s in STRATEGIES})
        print(f"{name}: {out}")
    # Monolithic: every strategy runs the hand-written monolithic tree, with the method's
    # shared subtrees (silence, turn limit, conclusion)
    shutil.copy(os.path.join(METHOD_XML, "common.xml"),
                os.path.join(HERE, "behavior_tree_xml", "monolithic"))
    write_config("monolithic", {s: "monolithic/monolithic.xml" for s in STRATEGIES})
    print("monolithic: config written")


if __name__ == "__main__":
    main()
