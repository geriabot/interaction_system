"""
Write the task cards of the sessions with real participants as Markdown, one file per card, so
that they can be read and reviewed exactly as the participant sees them (the panel shows the
same text, from the same sessions file):

    python3 evaluation/real/make_cards.py [--sessions evaluation/real/sessions_es.yaml] [--out DIR]

Writes <out>/es/<scenario id>.md (what the participant reads), <out>/en/<scenario id>.md (an English
translation for readers, from cards_en.yaml) and <out>/README.md (the index). Run it after changing
a card or its translation.
"""

import argparse
import os

import yaml

from sessions_common import card_text

HERE = os.path.dirname(os.path.abspath(__file__))


def strategy_of(scenario_id: str, scenarios: dict) -> str:
    return scenarios.get(scenario_id, {}).get("strategy", "")


def ending_of(scenario_id: str, scenarios: dict) -> str:
    """The outcome the conversation should end with: the planned one, or the strategy's own."""
    expect = scenarios.get(scenario_id, {}).get("expect", {})
    return expect.get("ending") or {"success": "completed", "cancelled": "cancelled"}.get(
        expect.get("outcome", "success"), "failed")


def card_lines(trial: dict, sessions: dict, sid: str, scenarios_file: str, scenarios: dict,
               english: bool) -> list[str]:
    note = (["*English translation for readers; the participants read the Spanish card "
             f"([es/{sid}.md](../es/{sid}.md)).*", ""] if english else [])
    return ([f"# {trial['title']}", ""] + note +
            ["What the participant reads:", "", "```text", card_text(trial, sessions), "```", "",
             "## For the experimenter", "",
             f"- Scenario: `{sid}` (`{os.path.basename(scenarios_file)}`), strategy "
             f"`{strategy_of(sid, scenarios)}`.",
             f"- Mechanism provoked: {scenarios.get(sid, {}).get('mechanism', '-')}; planned "
             f"ending: `{ending_of(sid, scenarios)}`.",
             f"- Detour: `{trial['detour']['kind']}` (off_task: an unrelated question; decline: "
             "a request the robot should decline; not_allowed: a value the task does not allow).",
             "- The card follows the scenario's `user_goal`, so that its ground truth (`expect`) "
             "scores the conversation.", ""])


def english_of(sessions: dict, path: str) -> dict:
    """The sessions file with the cards of cards_en.yaml (same ids and lines) in place of the
    Spanish ones."""
    with open(path, encoding="utf-8") as f:
        en = yaml.safe_load(f)
    by_id = {s["id"]: s for s in en["scenarios"]}
    missing = [t["id"] for t in sessions["scenarios"] if t["id"] not in by_id]
    if missing:
        raise SystemExit(f"{os.path.basename(path)} has no translation of {missing}")
    out = dict(sessions, detour_label=en["detour_label"], card_footer=en["card_footer"])
    out["scenarios"] = []
    for t in sessions["scenarios"]:
        e = by_id[t["id"]]
        if len(e["card"]) != len(t["card"]):
            raise SystemExit(f"{t['id']}: the translation has {len(e['card'])} lines, the card {len(t['card'])}")
        out["scenarios"].append(dict(t, title=e["title"], card=e["card"],
                                     detour=dict(t["detour"], text=e["detour"])))
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sessions", default=os.path.join(HERE, "sessions_es.yaml"))
    parser.add_argument("--english", default=os.path.join(HERE, "cards_en.yaml"),
                        help="The English translation of the cards (cards/en, for readers)")
    parser.add_argument("--out", default=os.path.join(HERE, "cards"))
    args = parser.parse_args()
    with open(args.sessions, encoding="utf-8") as f:
        sessions = yaml.safe_load(f)
    scenarios_file = os.path.join(os.path.dirname(args.sessions), sessions["scenarios_file"])
    with open(scenarios_file, encoding="utf-8") as f:
        scenarios = {s["id"]: s for s in yaml.safe_load(f)["scenarios"]}
    english = english_of(sessions, args.english)
    for lang in ("es", "en"):
        os.makedirs(os.path.join(args.out, lang), exist_ok=True)
    # Cards of an earlier layout, directly in cards/
    for old in os.listdir(args.out):
        if old.endswith(".md") and old != "README.md":
            os.remove(os.path.join(args.out, old))

    index = [
        "# Task cards of the sessions with real participants",
        "",
        f"Generated by `make_cards.py` from `{os.path.basename(args.sessions)}` and "
        f"`{os.path.basename(args.english)}`: do not edit by hand.",
        "The participants read the Spanish cards (`es/`), on a screen, exactly as in their files;",
        "`en/` is an English translation for readers who do not read Spanish. The lines under",
        "*For the experimenter* are not shown to the participant.",
        "",
        "Each card provokes one mechanism of the method on purpose (the scenario's `mechanism`), so",
        "that every mechanism is observed with people; the endings and the outcome are observed in all.",
        "",
        "| Card (Spanish) | English | Strategy | Mechanism provoked | Planned ending | Detour |",
        "|---|---|---|---|---|---|",
    ]
    for trial, trial_en in zip(sessions["scenarios"], english["scenarios"]):
        sid = trial["id"]
        for lang, t, s, eng in (("es", trial, sessions, False), ("en", trial_en, english, True)):
            with open(os.path.join(args.out, lang, f"{sid}.md"), "w", encoding="utf-8") as f:
                f.write("\n".join(card_lines(t, s, sid, scenarios_file, scenarios, eng)))
        index.append(f"| [{trial['title']}](es/{sid}.md) | [{trial_en['title']}](en/{sid}.md) | "
                     f"`{strategy_of(sid, scenarios)}` | "
                     f"{scenarios.get(sid, {}).get('mechanism', '-')} | "
                     f"`{ending_of(sid, scenarios)}` | {trial['detour']['kind']} |")
    with open(os.path.join(args.out, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(index) + "\n")
    print(f"{len(sessions['scenarios'])} cards in Spanish and English in {args.out}")


if __name__ == "__main__":
    main()
